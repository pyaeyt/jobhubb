<script>
$(document).ready(function() {
  // Contact form submission
  $('#contact-form').on('submit', function(e) {
    e.preventDefault();
    
    // Form validation
    let isValid = true;
    $(this).find('[required]').each(function() {
      if (!$(this).val()) {
        $(this).addClass('is-invalid');
        isValid = false;
      } else {
        $(this).removeClass('is-invalid');
      }
    });
    
    if (isValid) {
      // Simulate form submission
      $('#contact-form button[type="submit"]').html('<i class="fa fa-spinner fa-spin"></i> Sending...').prop('disabled', true);
      
      setTimeout(function() {
        $('#contact-form').prepend('<div class="alert alert-success">Thank you! Your message has been sent successfully. We\'ll get back to you soon.</div>');
        $('#contact-form button[type="submit"]').html('<i class="fa fa-check"></i> Message Sent').prop('disabled', false);
        $('#contact-form')[0].reset();
      }, 1500);
    }
  });
  
  // Remove validation class when user starts typing
  $('input, textarea').on('input', function() {
    if ($(this).val()) {
      $(this).removeClass('is-invalid');
    }
  });
  
  // Initialize accordion
  $('.panel-collapse').on('show.bs.collapse', function () {
    $(this).siblings('.panel-heading').addClass('active');
  });

  $('.panel-collapse').on('hide.bs.collapse', function () {
    $(this).siblings('.panel-heading').removeClass('active');
  });
});
</script>